test('a failing uninstall at local scope fails deploy before the old marketplace is removed', (t) => {
  const home = freshHome(t);
  const project = projectFolder(t);
  claudeLists(home, {
    marketplaces: JSON.stringify([marketplace('agent-config', REPO_ARGUMENT)]),
    plugins: JSON.stringify([{ id: 'ledger@agent-config', scope: 'local', projectPath: project }]),
  });
  failClaude(home, 'uninstall');

  const result = run(home, DEPLOY);

  assert.equal(result.status, 1, result.stdout);
  assert.ok(result.stderr.includes(`failed in ${project}`), result.stderr);
  assert.ok(!claudeCalls(home).includes(REMOVE_OLD_MARKETPLACE), claudeCalls(home).join('\n'));
});

