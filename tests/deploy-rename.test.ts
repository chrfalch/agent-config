test('a failing marketplace remove fails deploy before ledger is added', (t) => {
  const home = freshHome(t);
  claudeLists(home, { marketplaces: JSON.stringify([marketplace('agent-config', REPO_ARGUMENT)]) });
  failClaude(home, 'remove');

  const result = run(home, DEPLOY);

  assert.equal(result.status, 1, result.stdout);
  assert.notEqual(result.stderr.trim(), '');
  assert.ok(!claudeCalls(home).includes(ADD), claudeCalls(home).join('\n'));
});

test('deploy reads the manifest under its old name, then replaces it with the new one', (t) => {
  const home = freshHome(t);
  generatedRulesUnderOldName(home, '99-retired.md');

  const result = run(home, DEPLOY, '--no-mods');

  assert.equal(result.status, 0, result.stderr);
  assert.deepEqual(rulesIn(home), repoRules());
  assert.match(result.stdout, /^removed {2}~\/\.claude\/rules\/99-retired\.md$/m);
  assert.ok(existsSync(newManifest(home)), 'deploy writes the manifest under the new name');
  assert.ok(!existsSync(oldManifest(home)), 'deploy deletes the manifest under the old name');
});

test('--revert falls back to the manifest under its old name and removes it', (t) => {
  const home = freshHome(t);
  generatedRulesUnderOldName(home);

  const result = run(home, DEPLOY, '--revert');

  assert.equal(result.status, 0, result.stderr);
  assert.deepEqual(rulesIn(home), []);
  assert.ok(!existsSync(oldManifest(home)));
});

test('--revert removes the manifest under both names when both exist', (t) => {
  const home = freshHome(t);
  generatedRulesUnderOldName(home);
  writeFileSync(newManifest(home), '');

  const result = run(home, DEPLOY, '--revert');

  assert.equal(result.status, 0, result.stderr);
  assert.ok(!existsSync(newManifest(home)), 'revert deletes the manifest under the new name');
  assert.ok(!existsSync(oldManifest(home)), 'revert deletes the manifest under the old name');
});

test('a home deployed under the old name redeploys without a prompt or --force', (t) => {
  const home = freshHome(t);
  generatedRulesUnderOldName(home);
  claudeLists(home, {
    marketplaces: JSON.stringify([marketplace('agent-config', REPO_ARGUMENT)]),
    plugins: JSON.stringify([OLD_LEDGER_AT_USER]),
  });

  const result = run(home, DEPLOY);

  assert.equal(result.status, 0, result.stderr);
  assert.deepEqual(rulesIn(home), repoRules());
  assert.ok(rulesIn(home).every((name) => lstatSync(path.join(home, '.claude/rules', name)).isSymbolicLink()));
  assert.ok(existsSync(newManifest(home)));
  assert.ok(!existsSync(oldManifest(home)));
  assert.deepEqual(claudeState(home), { marketplaces: ['ledger'], plugins: ['ledger@ledger'] });
});
